import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { buildBinary } from '../src/binary.mjs';

const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(name, root), 'utf8');

test('binary wordmark keeps the handoff geometry and deterministic seed', () => {
  const rows = buildBinary();
  assert.equal(rows.length, 64);
  for (const row of rows) assert.equal(row.segs.map(segment => segment.text).join('').length, 112);
  assert.deepEqual(rows, buildBinary());
  assert.equal(createHash('sha256').update(JSON.stringify(rows)).digest('hex'), '334fd587026bd4273da75de22af433a450726c150d981ec1f277a67992bf47e4');
});

test('all generated templates contain resolved FreeMarker, not build tokens', async () => {
  for (const file of (await readdir(root)).filter(file => file.endsWith('.ftl'))) {
    const content = await read(file);
    assert.match(content, /Generated by npm run build/);
    assert.doesNotMatch(content, /__FW_FTL_|&lt;#|&lt;\/#/);
  }
  const login = await read('login.ftl');
  assert.match(login, /action="\$\{url.loginAction\}"/);
  assert.match(login, /name="credentialId"/);
  assert.match(login, /passkeys.conditionalUIData/);
  assert.match(login, /realm.resetPasswordAllowed/);
  assert.match(login, /social.providers as p/);
});

test('authentication is server driven, including reset confirmation', async () => {
  const otp = await read('login-otp.ftl');
  assert.match(otp, /name="otp"/);
  assert.match(otp, /selectedCredentialId/);
  assert.doesNotMatch(otp, /Trust this device|recovery code/i);
  const reset = await read('login-reset-password.ftl');
  assert.match(reset, /method="post"/);
  const info = await read('info.ftl');
  assert.match(info, /emailSentMessage/);
  assert.doesNotMatch(info, /15 minutes/);
});

test('session checks, locale URLs, and local assets are preserved', async () => {
  const layout = await read('template.ftl');
  assert.match(layout, /startSessionPolling/);
  assert.match(layout, /checkAuthSession/);
  assert.match(layout, /auth\.js\?v=[a-f0-9]{12}/);
  assert.match(layout, /\$\{style\}\?v=[a-f0-9]{12}/);
  assert.match(layout, /value="\$\{l.url\}"/);
  assert.doesNotMatch(layout, /fonts.googleapis|unpkg.com|jsdelivr/);
  const css = await read('flatwork.css');
  assert.match(css, /\.fw-input/);
  assert.match(css, /url\("\.\.\/fonts\/geist-400.woff2"\)/);
  assert.doesNotMatch(css, /url\([^)]*material-symbols/);
});

test('every ConfigMap entry is mounted and the map stays under Kubernetes limit', async () => {
  const kustomization = await read('../kustomization.yaml');
  const deployment = await read('../keycloak.yaml');
  const files = [...kustomization.matchAll(/- theme\/(\S+)/g)].map(match => match[1]);
  let size = 0;
  for (const file of files) {
    assert.ok(deployment.includes(`key: ${file},`), `missing mount: ${file}`);
    const content = await readFile(new URL(file, root));
    size += /\.woff2$/.test(file) ? Math.ceil(content.length / 3) * 4 : content.length;
  }
  assert.ok(size < 1_048_576, `ConfigMap too large: ${size}`);
});
