import { renderToStaticMarkup } from "react-dom/server";
import type { ReactNode } from "react";

// Only explicitly registered template expressions bypass React's HTML escaping.
// User data is still escaped by FreeMarker at request time; never decode HTML.
const expressions: string[] = [];
export function ftl(source: string): string {
  return `__FW_FTL_${expressions.push(source) - 1}__`;
}
export function Raw({ source }: { source: string }) {
  return ftl(source);
}
export function If({ test, children }: { test: string; children: ReactNode }) {
  return <><Raw source={`<#if ${test}>`} />{children}<Raw source="</#if>" /></>;
}
export function compile(element: ReactNode): string {
  let result = renderToStaticMarkup(element);
  // Nested components can register an expression which itself contains a token.
  while (/__FW_FTL_\d+__/.test(result)) {
    result = result.replace(/__FW_FTL_(\d+)__/g, (_, i) => expressions[Number(i)]);
  }
  return `<#-- Generated by npm run build from src/. Do not edit directly. -->\n${result}\n`;
}
export const msg = (key: string) => ftl(`\${msg("${key}")}`);
